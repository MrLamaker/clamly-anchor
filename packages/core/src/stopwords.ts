/**
 * Returns the built-in stop words for a BCP 47 locale. Without a locale the
 * English list is used, matching earlier releases. Unknown languages get no
 * stop words rather than another language's list.
 */
export function getStopWords(locale?: string): readonly string[] {
  if (locale === undefined) return STOP_WORDS["en"] ?? [];
  const language = locale.split(/[-_]/)[0]?.toLowerCase() ?? "";
  return STOP_WORDS[language] ?? [];
}
